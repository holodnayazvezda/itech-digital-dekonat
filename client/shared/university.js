export function transferRequirements(target, person) {
  const track = programTracks[target];
  if (!track || !person.program) return [];
  const completedTerms = (person.course || 2) * 2 - 2;
  const completed = new Set(
    curriculum(person.program)
      .slice(0, completedTerms)
      .flat()
      .map((x) => x.subject)
      .concat(
        person.id === "friend"
          ? ["Анализ данных", "Иностранный язык"]
          : person.id === "student" ? ["Анализ данных", "Проектный семинар", "Иностранный язык"] : [],
      ),
  );
  return ["Математика", "Академическое письмо", track[0], track[1]].map(
    (subject) => ({ subject, met: completed.has(subject) }),
  );
}
