import {test,expect} from "@playwright/test";

test("компактная история, серый статус, новое окно и скачивание PDF",async({page})=>{
  const errors=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/");await page.getByRole("button",{name:"Войти",exact:true}).click();
  await expect(page.locator(".shell")).toBeVisible();
  const token=await page.evaluate(()=>sessionStorage.getItem("atlas-session"));
  const created=await page.request.post("/api/campus/request",{headers:{Authorization:"Bearer "+token},data:{kind:"document",name:"Справка об обучении",format:"Электронная",values:{destination:"Учебная библиотека"}}});
  expect(created.ok(),await created.text()).toBe(true);const record=await created.json();
  const office=await page.request.post("/api/campus/login",{data:{role: "office", password:"OfficeHelp2026!"}});
  const {token:officeToken}=await office.json();
  const decision=await page.request.post("/api/campus/decision",{headers:{Authorization:"Bearer "+officeToken},data:{id:record.id,status:"approved"}});
  expect(decision.ok()).toBe(true);
  await page.reload();
  await page.getByRole("navigation", { name: "Навигация кабинета", exact: true }).getByRole("button",{name:"Сервисы",exact:true}).click();
  await page.getByRole("button",{name:"Мои заявки",exact:true}).click();
  const row=page.locator(".requests-list .case-row").filter({hasText:"Справка об обучении"}).first();
  await expect(row).toContainText("Одобрена");
  await expect(row.locator(".badge")).not.toHaveCSS("background-color","rgb(217, 237, 223)");
  expect((await row.boundingBox()).height).toBeLessThan(100);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`docs/requests-${page.viewportSize().width}.png`});
  await row.click();
  const dialog=page.getByRole("dialog",{name:"Заявка",exact:true});
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole("heading",{name:"Справка об обучении",exact:true})).toBeVisible();
  await expect(dialog.locator(".result-card.approved")).toHaveCSS("background-color","rgba(0, 0, 0, 0)");
  await expect(dialog).toContainText("Учебная библиотека");
  expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await page.screenshot({path:`docs/request-details-${page.viewportSize().width}.png`});
  const waiting=page.waitForEvent("download");
  await dialog.getByRole("button",{name:"Скачать PDF",exact:true}).click();
  const download=await waiting;
  expect(download.suggestedFilename()).toMatch(/\.pdf$/);
  expect(await download.failure()).toBe(null);
  await page.keyboard.press("Escape");
  await expect(dialog).not.toBeVisible();
  await expect(row).toBeFocused();
  expect(errors).toEqual([]);
});
