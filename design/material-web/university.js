export function transferRequirements(target, person) {
  const i = programNames.indexOf(target);
  if (i < 0 || !person.program) return [];
  const completed = new Set(
    curriculum(person.program)
      .slice(0, 2)
      .flat()
      .map((x) => x.subject)
      .concat(
        person.id === "friend"
          ? ["Анализ данных", "Иностранный язык"]
          : ["Анализ данных", "Проектный семинар", "Иностранный язык"],
      ),
  );
  return ["Математика", "Академическое письмо", tracks[i][0], tracks[i][1]].map(
    (subject) => ({ subject, met: completed.has(subject) }),
  );
}
